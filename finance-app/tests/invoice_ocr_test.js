// Разбор счёта по тексту «как после распознавания скана» (OCR): lib/domain.js → parseInvoiceText(text, { ocr: true }) и ocrNormalize.
// Шум: латинские буквы-двойники в русских словах, «О/З/l» вместо цифр, «N°/Ns» вместо «№», лишние пробелы и пробел перед двоеточием.
// Образцы вымышленные. node tests/invoice_ocr_test.js
'use strict';
const D = require('../lib/domain');
let ok = 0, bad = 0;
const eq = (name, got, want) => { if (JSON.stringify(got) === JSON.stringify(want)) ok++; else { bad++; console.log(`✗ ${name}: ждали ${JSON.stringify(want)}, получили ${JSON.stringify(got)}`); } };

// 1) 1С-счёт после OCR
const s1 = `Поставщик :  БИН / ИИН  123456789О12,  ТОО "Стройкомплект  Алматы"
Cчeт нa oплaту  N°  1З7  от 2О  сентября 2О26 г.
Покупатель :  ТОО "MOST Project"
№ Наименование Кол-во Ед. Цена Сумма
1  Бетон  М3ОО  1О  м3  28 5ОО,ОО  285 ООО,ОО
2  Арматура  А5ОО  2  т  4О5 ООО  81О ООО,ОО
ИTOГO : 1 О95 ООО,ОО
В т.ч. НДС 16% : 151 О34,48
Всего к оплате : 1 О95 ООО,ОО`;
const r1 = D.parseInvoiceText(s1, { ocr: true });
eq('1С номер', r1.number, '137');
eq('1С дата (месяц словом)', r1.invoiceDate, '2026-09-20');
eq('1С поставщик', r1.contractor, 'ТОО "Стройкомплект Алматы"');
eq('1С компания', r1.company, 'MOST Project');
eq('1С сумма (О→0, пробел перед двоеточием)', r1.amount, 1095000);

// 2) Kaspi-счёт после OCR: «Получатель/Плательщик», сумма без копеек, «З» вместо 3
const s2 = `Получатель
TOO "Ромашка Трейд" Сч. № KZ00722S000000000000
CЧET Ns 5OO1/2 от 25.О9.2О26 15:О7:16
Плательщик: Товарищество с ограниченной ответственностью "MOST Architects" ИИН 000000000000, РК,
г. Алматы
Итого :  6 7З6
Всего наименований 2, на сумму 67З6 тг.`;
const r2 = D.parseInvoiceText(s2, { ocr: true });
eq('Kaspi номер', r2.number, '5001/2');
eq('Kaspi дата', r2.invoiceDate, '2026-09-25');
eq('Kaspi поставщик (латинское TOO)', r2.contractor, 'ТОО "Ромашка Трейд"');
eq('Kaspi компания', r2.company, 'MOST Architects');
eq('Kaspi сумма (З→3)', r2.amount, 6736);

// 3) нормализация: что меняем и что нет
const n = D.ocrNormalize;
eq('сумма с буквами', n('Итого : 6 З00,О0'), 'Итого: 6 300,00');
eq('дата', n('от 2О.О9.2О26'), 'от 20.09.2026');
eq('№', n('Счет N° 12'), 'Счет № 12');
eq('русское слово с латиницей', n('Cчeт нa oплaту'), 'Счет на оплату');
eq('IBAN не трогаем', n('KZ00722S0000000О0000'), 'KZ00722S0000000О0000');
eq('«корпус 1Б» не трогаем', n('корпус 1Б'), 'корпус 1Б');
eq('слова без цифр не трогаем', n('ТОО Орда ООО'), 'ТОО Орда ООО');
eq('пробелы вокруг запятой в копейках', n('6 756 , 00'), '6 756,00');
// без флага ocr — разбор как раньше (текстовый PDF не меняется)
eq('без ocr: «1О95» не чинится', D.parseInvoiceText('Итого: 1О95').amount, 1);

console.log(`Итого: ✓ ${ok}  ✗ ${bad}`); process.exit(bad ? 1 : 0);
