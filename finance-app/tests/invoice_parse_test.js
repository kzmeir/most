// Разбор текста PDF-счёта (lib/domain.js → parseInvoiceText). Образцы вымышленные, по формату реальных счетов.
// node tests/invoice_parse_test.js
'use strict';
const D = require('../lib/domain');
let ok = 0, bad = 0;
const eq = (name, got, want) => { if (JSON.stringify(got) === JSON.stringify(want)) ok++; else { bad++; console.log(`✗ ${name}: ждали ${JSON.stringify(want)}, получили ${JSON.stringify(got)}`); } };

// 1) Kaspi-счёт: «Получатель», «Плательщик», сумма без копеек, НДС в строке позиции
const kaspi = D.parseInvoiceText(`ТОО "Ромашка Трейд"
Республика Казахстан, г. Алматы
Получатель
ТОО "Ромашка Трейд" Сч. № KZ00722S000000000000
СЧЕТ № 5001/2 от 25.09.2026 15:07:16
Плательщик: Товарищество с ограниченной ответственностью "MOST Architects" ИИН 000000000000, РК,
г. Алматы
№ Наименование товара Кол-во Ед. Цена, тг. Ставка НДС Сумма, тг.
1 Коврик для мыши 1 шт 991 16% 991
2 Клавиатура 1 шт 5 765 16% 5 765
В том числе НДС: 932
Итого: 6 756
Всего наименований 2, на сумму 6756 тг.`);
eq('kaspi номер', kaspi.number, '5001/2');
eq('kaspi дата', kaspi.invoiceDate, '2026-09-25');
eq('kaspi поставщик', kaspi.contractor, 'ТОО "Ромашка Трейд"');
eq('kaspi компания', kaspi.company, 'MOST Architects');
eq('kaspi сумма', kaspi.amount, 6756);
eq('kaspi назначение', kaspi.purpose, 'Счёт № 5001/2: Коврик для мыши; Клавиатура');

// 2) 1С-счёт: покупатель разорван переносом строки, сумма с копейками
const c1 = D.parseInvoiceText(`Бенефициар: ИИК Кбе
Индивидуальный предприниматель "Лютик"
KZ00722S000000000000 19
Счет на оплату № 112 от 24 сентября 2026 г.
Поставщик: БИН / ИИН 000000000000,Индивидуальный предприниматель "Лютик",Республика Казахстан
Покупатель: БИН / ИИН 000000000000,Товарищество с ограниченной ответственностью "MOST
Architects",050000, город Алматы
№ Код Наименование Кол-во Ед. Цена Сумма
1 704-1 Выключатель 2 шт 1 000,00 2 000,00
Итого: 24 520,00
Всего к оплате: 24 520,00`);
eq('1С номер', c1.number, '112');
eq('1С дата', c1.invoiceDate, '2026-09-24');
eq('1С поставщик', c1.contractor, 'Индивидуальный предприниматель "Лютик"');
eq('1С компания (перенос строки)', c1.company, 'MOST Architects');
eq('1С сумма', c1.amount, 24520);

// 3) Классический счёт: всё в одной строке
const plain = D.parseInvoiceText(`Счет на оплату № 43 от 24.09.2026
Поставщик: ТОО «Василёк»
Покупатель: ТОО "MOST Project"
Всего к оплате: 1 500 000,00`);
eq('обычный поставщик', plain.contractor, 'ТОО «Василёк»');
eq('обычный компания', plain.company, 'MOST Project');
eq('обычный сумма', plain.amount, 1500000);

// 4) Наши компании
eq('ИП MOST Design', D.companyOf('ИП MOST Design'), 'ИП MOST Design');
eq('ИП PANA Design', D.companyOf('ИП PANA Design'), 'ИП PANA Design');

// 5) Скан (текста нет) — пусто, без ошибок
eq('скан', D.parseInvoiceText('').amount, 0);

console.log(`Итого: ✓ ${ok}  ✗ ${bad}`);
process.exit(bad ? 1 : 0);
